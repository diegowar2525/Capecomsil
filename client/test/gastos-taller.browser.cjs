// Interacciones con API simulada: no modifica datos reales.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
    const { createServer } = await import('vite');
    const server = await createServer({ server: { port: 0, host: '127.0.0.1', open: false, hmr: false } });
    await server.listen();
    let browser;
    try {
        browser = await chromium.launch({ channel: 'msedge', headless: true });
        const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
        page.setDefaultTimeout(10000);
        const errors = [];
        const mutations = [];
        page.on('pageerror', error => errors.push(error.message));
        const trabajo = { id_mantenimiento: 1, id_vehiculo: 1, placa: 'ABC-123', clase: 'CORRECTIVO', tipo: 'Frenos', monto: '25.00', estado: 'REGISTRADO', total_pagado: '0', saldo_pendiente: '25.00', detalles: [], pagos: [] };
        await page.route('**/api/**', async route => {
            const req = route.request();
            const path = new URL(req.url()).pathname;
            const json = data => route.fulfill({ contentType: 'application/json', body: JSON.stringify(data) });
            if (path === '/api/auth/me') return json({ usuario: { id_usuario: 1, nombre: 'Prueba', rol: 'OPERADOR', activo: true }, permisos: ['gastos.consultar','gastos.crear','mantenimientos.consultar','mantenimientos.pagar','mantenimientos.crear','mantenimientos.editar','mantenimientos.historial','compras.crear','mantenimientos.finalizar','mantenimientos.registrar_cumplimientos'], fecha_expiracion: '2099-01-01' });
            if (req.method() !== 'GET') { mutations.push({ path, data: req.postDataJSON() }); return json({ id_gasto: 1 }); }
            if (path === '/api/proveedores') return json([{id_proveedor:1,nombre:'Taller prueba'}]);
            if (path === '/api/tipos-gasto') return json([{id_tipo_gasto:3,nombre:'Peaje',estado:true}]);
            if (path === '/api/informes/viaticos') return json([{id_viatico_chofer:7,nombre:'Chofer prueba',estimado:'12.00',gasto_real_registrado:'0.00'}]);
            if (path === '/api/vehiculos') return json([{id_vehiculo:1,placa:'ABC-123'},{id_vehiculo:2,placa:'OTRO-456'}]);
            if (path === '/api/planes-mantenimiento') return json([{id_plan_mantenimiento_vehiculo:1,id_vehiculo:1,nombre:'Aceite',intervalo_km:8000,estado:true,placa:'ABC-123'},{id_plan_mantenimiento_vehiculo:2,id_vehiculo:2,nombre:'Plan ajeno',intervalo_km:8000,estado:true},{id_plan_mantenimiento_vehiculo:3,id_vehiculo:1,nombre:'Plan inactivo',estado:false}]);
            if (path === '/api/mantenimientos/1') return json(trabajo);
            if (path === '/api/mantenimientos') return json([trabajo]);
            return json([]);
        });
        const base = `http://127.0.0.1:${server.httpServer.address().port}`;
        await page.goto(base + '/#/gastos');
        await page.getByRole('button', {name:/Registrar gasto/}).click();
        await page.getByLabel('¿Qué deseas registrar?').selectOption('VIATICO');
        await page.getByLabel('Día del viático').fill('2026-10-30');
        await page.getByLabel('Chofer y viático diario').selectOption('7');
        await page.getByText('Estimado: $ 12.00', {exact:false}).waitFor();
        await page.getByLabel('Fecha del desembolso').fill('2026-10-31');
        await page.getByLabel('Monto desembolsado').fill('6');
        await page.setViewportSize({width:390,height:844});
        const box = await page.getByRole('dialog').boundingBox();
        assert.ok(box.x >= 0 && box.x + box.width <= 390);
        await page.getByRole('button',{name:'Guardar cambios',exact:true}).click();
        await page.getByRole('dialog').waitFor({state:'hidden'});
        assert.equal(mutations[0].data.origen,'VIATICO');
        assert.equal(mutations[0].data.id_viatico_chofer,'7');
        assert.equal(mutations[0].data.id_tipo_gasto,undefined);
        await page.setViewportSize({width:1280,height:900});
        await page.goto(base + '/#/mantenimiento');
        await page.getByRole('button',{name:'Ver detalle',exact:true}).click();
        await page.getByRole('button',{name:'Registrar pago al taller',exact:true}).click();
        await page.getByLabel('Fecha del pago').fill('2026-10-31');
        await page.getByLabel('Monto pagado').fill('10');
        await page.getByRole('button',{name:'Registrar pago al taller',exact:true}).last().click();
        await page.getByRole('dialog').waitFor({state:'hidden'});
        assert.equal(mutations[1].path,'/api/mantenimientos/1/pagos');
        trabajo.id_factura_proveedor = 2;
        await page.getByRole('button',{name:'Ver detalle',exact:true}).click();
        await page.getByRole('dialog').getByText('Saldo pendiente',{exact:true}).waitFor();
        assert.equal(await page.getByRole('button',{name:'Registrar pago al taller',exact:true}).count(),0);
        assert.equal(await page.getByRole('button',{name:'Vincular un plan',exact:true}).count(),0);
        await page.getByRole('button',{name:'Cerrar',exact:true}).click();
        await page.getByRole('button',{name:/Registrar trabajo/}).click();
        await page.getByRole('dialog').getByLabel('Clase de trabajo',{exact:true}).scrollIntoViewIfNeeded();
        await page.getByRole('dialog').getByLabel('Clase de trabajo',{exact:true}).selectOption('PREVENTIVO');
        await page.getByRole('dialog').getByLabel('Vehículo',{exact:true}).selectOption('1');
        await page.getByLabel('Fin (opcional)',{exact:true}).fill('2026-10-30T10:00');
        await page.getByRole('checkbox',{name:/Aceite/}).check();
        assert.equal(await page.getByRole('checkbox',{name:/Plan ajeno|Plan inactivo/}).count(),0);
        await page.getByRole('dialog').getByLabel('Vehículo',{exact:true}).selectOption('2');
        assert.equal(await page.getByRole('checkbox',{name:/Aceite/}).count(),0);
        await page.getByRole('dialog').getByLabel('Vehículo',{exact:true}).selectOption('1');
        assert.equal(await page.getByRole('checkbox',{name:/Aceite/}).isChecked(),false);
        await page.getByRole('dialog').getByLabel('Clase de trabajo',{exact:true}).selectOption('CORRECTIVO');
        assert.equal(await page.locator('.planes-cumplidos').count(),0);
        await page.getByRole('button',{name:'Cerrar',exact:true}).click();
        trabajo.clase = 'PREVENTIVO';
        trabajo.fecha_fin = '2026-10-30T10:00:00';
        trabajo.cumplimientos = [{id_cumplimiento_plan_mantenimiento:1,id_plan_mantenimiento_vehiculo:1,nombre_plan:'Aceite',kilometraje_aplicado:'48000'}];
        await page.getByRole('button',{name:'Ver detalle',exact:true}).click();
        await page.getByRole('cell',{name:'Aceite',exact:true}).waitFor();
        await page.getByRole('button',{name:'Vincular un plan',exact:true}).click();
        await page.getByText('No hay planes activos pendientes de vincular para este vehículo.',{exact:true}).waitFor();
        assert.equal(await page.getByRole('checkbox').count(),0);
        await page.getByRole('button',{name:'Cerrar',exact:true}).click();
        Object.assign(trabajo,{id_factura_proveedor:null,version:3,pago_directo_automatico:true,clase:'CORRECTIVO',cumplimientos:[],fecha_inicio:'2026-10-30T08:00:00'});
        await page.getByRole('button',{name:'Editar',exact:true}).click();
        const dialog = page.getByRole('dialog');
        await dialog.getByLabel('Total cobrado por el taller').fill('30');
        assert.equal(await dialog.getByLabel('Forma de registro').isDisabled(),true);
        assert.equal(await dialog.getByLabel(/Motivo/).count(),0);
        await dialog.getByRole('button',{name:'Guardar cambios',exact:true}).click();
        await dialog.waitFor({state:'hidden'});
        assert.equal(mutations.at(-1).data.version,3);
        assert.equal(mutations.at(-1).data.monto,'30');
        await page.getByRole('button',{name:/Registrar trabajo/}).click();
        await dialog.getByLabel('Forma de registro').selectOption('NUEVA');
        await dialog.getByLabel('Clase de trabajo',{exact:true}).selectOption('CORRECTIVO');
        await dialog.getByLabel('Vehículo',{exact:true}).selectOption('1');
        await dialog.getByLabel('Proveedor',{exact:true}).selectOption('1');
        await dialog.getByLabel('Inicio',{exact:true}).fill('2026-11-01T08:00');
        await dialog.getByLabel('Trabajo realizado',{exact:true}).fill('Frenos');
        await dialog.getByLabel('Número de factura').fill('TALLER-UI');
        await dialog.getByLabel('Emisión',{exact:true}).fill('2026-11-01');
        const conceptos = dialog.getByRole('group',{name:'Servicio del trabajo',exact:true});
        assert.equal(await conceptos.getByLabel('Tipo',{exact:true}).inputValue(),'SERVICIO');
        assert.equal(await conceptos.getByLabel('Descripción',{exact:true}).inputValue(),'Frenos');
        await conceptos.getByLabel('Cantidad',{exact:true}).fill('1');
        await conceptos.getByLabel('Precio unitario').fill('100');
        await conceptos.getByLabel('Descuento (opcional)',{exact:true}).fill('0');
        await conceptos.getByLabel('Impuesto (%)').fill('15');
        assert.equal(await dialog.getByLabel('Total cobrado por el taller').count(),0);
        await dialog.getByRole('button',{name:'Guardar cambios',exact:true}).click();
        await dialog.waitFor({state:'hidden'});
        assert.equal(mutations.at(-1).data.modalidad_pago,'NUEVA');
        assert.equal(mutations.at(-1).data.factura.detalles[0].porcentaje_impuesto,'15');
        assert.equal(mutations.at(-1).data.monto,undefined);
        assert.deepEqual(errors,[]);
        console.log('OK: viático real, diseño móvil y pago directo/por factura.');
    } finally { await browser?.close(); await server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
